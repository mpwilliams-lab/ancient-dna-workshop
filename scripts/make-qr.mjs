// Pre-renders the wrap-screen QR code for the GitHub Pages URL as an inline SVG string.
// Usage: node scripts/make-qr.mjs [outFile]   (default: src/generated/qr.ts)
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import QRCode from 'qrcode';

const PAGES_URL = 'https://mpwilliams-lab.github.io/ancient-dna-workshop/';
const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(process.argv[2] ?? resolve(here, '../src/generated/qr.ts'));

const svg = await QRCode.toString(PAGES_URL, {
  type: 'svg',
  errorCorrectionLevel: 'M',
  margin: 4,
  color: { dark: '#000000', light: '#ffffff' },
});

const source =
  '// GENERATED by scripts/make-qr.mjs. Do not edit by hand; run `node scripts/make-qr.mjs`.\n' +
  `export const QR_URL = ${JSON.stringify(PAGES_URL)};\n` +
  `export const QR_SVG = ${JSON.stringify(svg.trim())};\n`;

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, source, 'utf8');
console.log(`make-qr: wrote ${out} (${source.length} bytes) for ${PAGES_URL}`);
