// npm run credits: writes CREDITS.md at the repo root from assets/manifest.json (spec §7.2), listing every image bundled in
// src/assets/img/ or src/assets/svg/ (the same set the in-app credits panel lists, src/credits.ts).  --check exits 1 when
// CREDITS.md is stale.  --print prints { footer, attributions } as JSON; tests/credits.test.ts compares it with
// src/assetManifest.ts and src/content.ts so the formats cannot drift apart.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const MANIFEST = join(ROOT, 'assets/manifest.json');
const OUT = join(ROOT, 'CREDITS.md');

// Must equal CREDITS_FOOTER in src/content.ts (pinned by tests/credits.test.ts).
const CREDITS_FOOTER =
  'Map outlines: Made with Natural Earth (public domain). Allele frequencies: 1000 Genomes Project; gnomAD; Akbari et al. 2026 (AGES). ' +
  'Lactase data: Liebert et al. 2017, Human Genetics (CC BY 4.0). The app\'s code licence does not cover these images; each keeps its own licence.';

function attribution(e) {
  if (e.licence === 'own') return e.author;
  if (e.licence === 'CC0' || e.licence === 'PD') return `Photo: ${e.author} (${e.licence === 'CC0' ? 'CC0' : 'public domain'}), via ${e.source}`;
  return `"${e.title}" by ${e.author}, ${e.licence} (${(e.licence_url ?? '').replace(/^https:\/\//, '')}), via ${e.source}; ${e.changes}`;
}

function bundledIds() {
  const names = (dir, ext) => (existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith(ext)).map((f) => f.slice(0, -ext.length)) : []);
  return new Set([...names(join(ROOT, 'src/assets/img'), '.jpg'), ...names(join(ROOT, 'src/assets/svg'), '.svg')]);
}

/**
 * The "Changes:" line of one credit. "cropped" appears only where a crop box was really applied to the file (`crop`), never because
 * the manifest merely ALLOWS cropping (`ops`): the app shows every photo whole, so a photo is only resized unless it has a box.
 * CC BY / BY-SA entries carry their line in `changes` (src/assetManifest.ts checks it against the box); CC0 and public-domain
 * entries have none, so it is derived here the same way.
 */
function changesLine(e) {
  if (e.kind === 'own-svg') return 'none';
  return e.changes ?? (e.crop ? 'cropped and resized' : 'resized');
}

function render(manifest, bundled) {
  const lines = [
    '# Image and data credits',
    '',
    'Generated by `npm run credits` from `assets/manifest.json`. Do not edit by hand.',
    '',
    "The licence of this repository's code does not cover the images below: each image keeps its own licence.",
    'An image is bundled into the app only after the instructor has checked it.',
    'Photos are shown whole in the app. A credit that says "cropped and resized" names a photo that was cropped before it was resized; every other photo was only resized.',
    '',
    '## Images',
    '',
  ];
  const shown = manifest.images.filter((e) => bundled.has(e.id));
  if (shown.length === 0) lines.push('No images are bundled yet.', '');
  let card = '';
  for (const e of shown) {
    if (e.card !== card) {
      card = e.card;
      lines.push(`### Card ${card}`, '');
    }
    lines.push(`- ${attribution(e)}`);
    if (e.file_page) lines.push(`  - File page: ${e.file_page}`);
    lines.push(`  - Licence: ${e.licence === 'own' ? 'drawn for this workshop' : e.licence}${e.licence_url ? ` (${e.licence_url})` : ''}`);
    lines.push(`  - Changes: ${changesLine(e)}`);
    lines.push('');
  }
  lines.push('## Data and maps', '', CREDITS_FOOTER, '');
  return lines.join('\n');
}

const manifest = JSON.parse(readFileSync(MANIFEST, 'utf8'));
const arg = process.argv[2];
if (arg === '--print') {
  console.log(JSON.stringify({ footer: CREDITS_FOOTER, attributions: Object.fromEntries(manifest.images.map((e) => [e.id, attribution(e)])) }));
} else {
  const bundled = bundledIds();
  const text = render(manifest, bundled);
  if (arg === '--check') {
    const now = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
    if (now !== text) {
      console.error('make-credits: CREDITS.md is out of date. Run npm run credits and commit it.');
      process.exit(1);
    }
    console.log('make-credits: CREDITS.md is up to date.');
  } else {
    writeFileSync(OUT, text);
    console.log(`make-credits: wrote CREDITS.md (${manifest.images.filter((e) => bundled.has(e.id)).length} bundled image(s)).`);
  }
}
